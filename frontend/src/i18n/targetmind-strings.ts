type TMKey = keyof (typeof STRINGS)["en"];

export function useTMText() {
  const { i18n } = useTranslation();
  // `i18n` can be undefined when rendered outside an I18nextProvider (or when
  // a test stubs `useTranslation`), so fall back to English rather than crash.
  const lang = (i18n?.language || "en").toLowerCase().startsWith("zh")
    ? "zh"
    : "en";
  return (key: TMKey): string => STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}
